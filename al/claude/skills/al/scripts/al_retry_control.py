"""Closed finite call-site mapping to the authenticated sealed retry context."""
import sys


def current():
    return getattr(sys.modules.get('_al_retry_control_context'),'client',None)


def git(args, root=None):
    client=current()
    if client is None:return None
    args=tuple(args)
    forms={
        ('rev-parse','--show-toplevel'):'top',
        ('rev-parse','--show-toplevel','--git-dir','--git-common-dir'):'repository_identity',
        ('rev-parse','--git-common-dir','--show-object-format'):'object_binding',
        ('rev-parse','HEAD'):'head',
        ('rev-parse','--verify','HEAD^{commit}'):'head_verify',
        ('ls-files','--stage','-z'):'index',
        ('ls-files','--others','--exclude-standard','-z'):'untracked',
        ('ls-files','--cached','-z'):'cached',
        ('status','--ignore-submodules=all','--porcelain'):'status',
        ('status','--porcelain=v1','-z','--untracked-files=all','--ignore-submodules=none'):'child_status',
    }
    if args in forms:return client.git(forms[args],root=root)
    if len(args)==6 and args[:4]==('rev-parse','--git-common-dir','--git-dir','--end-of-options') and args[-1]=='HEAD^{commit}' and args[4].endswith('^{commit}'):
        return client.git('scope_identity',{'revision':args[4][:-9]},root)
    if len(args)==3 and args[:2]==('merge-base','HEAD'):
        return client.git('merge_base',{'revision':args[2]},root)
    if len(args)==4 and args[:3]==('ls-tree','-r','-z'):
        return client.git('tree',{'revision':args[3]},root)
    if len(args)==4 and args[:3]==('ls-tree','-rlz','--full-tree'):
        return client.git('long_tree',{'revision':args[3]},root)
    if len(args)==5 and args[:4]==('ls-tree','-r','-l','-z'):
        return client.git('inventory_tree',{'revision':args[4]},root)
    if args[:1]==('diff',):
        if len(args)==4 and args[1:3]==('--name-only','-z'):
            return client.git('currency_diff',{'revision':args[3]},root)
        if len(args) in {5,6} and args[1] in {'--ignore-submodules=all','--ignore-submodules=none'} and args[-1]=='--':
            mode=args[2:-2]
            if mode not in {('--binary',),('--name-only','-z')}:raise ValueError('unsupported sealed diff')
            return client.git('parent_diff',{'revision':args[-2],'binary':mode==('--binary',),'ignore':args[1].split('=')[1]},root)
    if len(args)==4 and args[:3]==('ls-files','-z','--'):
        return client.git('ledger_tracked',{'path':args[3]},root)
    if len(args)==6 and args[:5]==('ls-tree','-r','--name-only','HEAD','--'):
        return client.git('ledger_tree',{'path':args[5]},root)
    if len(args)>6 and args[:6]==('ls-files','-z','--cached','--others','--exclude-standard','--'):
        return client.git('ledger_scope',{'paths':list(args[6:])},root)
    # The inventory excludes are generated by this closed source, not forwarded by the broker.
    from al_repository_facts import EXCLUDED
    excluded=tuple(v for name in sorted(EXCLUDED) for v in ('--exclude='+name+'/','--exclude=**/'+name+'/'))
    patterns={
        ('ls-files','--others','--exclude-per-directory=.gitignore',*excluded,'-z'):'inventory_untracked',
        ('ls-files','--others','--cached','--exclude-per-directory=.gitignore',*excluded,'-z','--','.gitignore',':(glob)**/.gitignore'):'inventory_ignores',
        ('ls-files','--others','--ignored','--directory','--exclude-per-directory=.gitignore',*excluded,'-z'):'inventory_ignored',
    }
    if args in patterns:return client.git(patterns[args],root=root)
    if len(args)==6 and args[:5]==('ls-files','--others','-z','--',args[4]):
        raise ValueError('unsupported sealed inventory operands')
    if len(args)==5 and args[:4]==('ls-files','--others','-z','--'):
        return client.git('inventory_scope',{'path':args[4]},root)
    raise ValueError('unsupported sealed Git form')
